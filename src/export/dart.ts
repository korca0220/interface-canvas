import { formatFieldType, formatParams } from '../model/signature'
import type { Doc, Field, InterfaceNode, Method } from '../model/types'

/**
 * 문서(또는 선택한 노드)를 Dart 코드로 변환한다.
 *
 * - interface → `abstract interface class`, abstract → `abstract class`
 * - class → 구현체: depends 관계는 생성자 주입 private 필드, 메서드는 `throw UnimplementedError()` 스텁.
 *   implements/extends 대상의 멤버 중 빠진 것은 @override 스텁으로 채운다.
 * - model → final 필드 + const 생성자
 * - enum → enum 값
 * - memo는 `///` 문서 주석으로 붙인다.
 */
export function toDart(doc: Doc, ids?: string[]): string {
  const targets = ids ? doc.interfaces.filter((n) => ids.includes(n.id)) : doc.interfaces
  const blocks = targets.map((n) => nodeToDart(doc, n))
  const header = ids ? '' : `// ${doc.name || 'Untitled'} — generated by Interface Canvas\n\n`
  return header + blocks.join('\n\n') + (blocks.length ? '\n' : '')
}

const I = '  '

export function lowerCamel(name: string): string {
  const base = name.replace(/<.*$/, '')
  const m = base.match(/^[A-Z]+(?=[A-Z][a-z0-9])|^[A-Z]+$|^[A-Z]/)
  if (!m) return base
  return m[0].toLowerCase() + base.slice(m[0].length)
}

function docComment(memo: string, indent = ''): string[] {
  const text = memo.trim()
  if (!text) return []
  return text.split('\n').map((l) => (l.trim() ? `${indent}/// ${l.trimEnd()}` : `${indent}///`))
}

function byId(doc: Doc, id: string): InterfaceNode | undefined {
  return doc.interfaces.find((n) => n.id === id)
}

function targetsOf(doc: Doc, node: InterfaceNode, type: string): InterfaceNode[] {
  return doc.relations
    .filter((r) => r.from === node.id && r.type === type)
    .map((r) => byId(doc, r.to))
    .filter((n): n is InterfaceNode => !!n)
}

/**
 * implements/extends로 이어진 모든 상위 타입 (순환 방지).
 * mustImplement: 구현체가 직접 구현해야 하는 멤버를 가진 타입인지
 * (implements 경로로 도달했거나 interface/abstract인 경우). 구체 클래스를 extends하면 상속받으므로 false.
 */
function supertypes(doc: Doc, node: InterfaceNode): { node: InterfaceNode; mustImplement: boolean }[] {
  const seen = new Set<string>([node.id])
  const out: { node: InterfaceNode; mustImplement: boolean }[] = []
  const next = (n: InterfaceNode, viaImpl: boolean) => [
    ...targetsOf(doc, n, 'extends').map((t) => ({ t, viaImpl })),
    ...targetsOf(doc, n, 'implements').map((t) => ({ t, viaImpl: true })),
  ]
  const queue = next(node, false)
  while (queue.length) {
    const { t, viaImpl } = queue.shift()!
    if (seen.has(t.id)) continue
    seen.add(t.id)
    out.push({ node: t, mustImplement: viaImpl || t.kind === 'interface' || t.kind === 'abstract' })
    queue.push(...next(t, viaImpl))
  }
  return out
}

const methodSig = (m: Method) => `${m.returns} ${m.name}(${formatParams(m.params)})`
const getterSig = (f: Field) => `${formatFieldType(f)} get ${f.name}`

function header(doc: Doc, node: InterfaceNode): { line: string; notes: string[] } {
  const prefix: Record<InterfaceNode['kind'], string> = {
    interface: 'abstract interface class',
    abstract: 'abstract class',
    class: 'class',
    model: 'class',
    enum: 'enum',
  }
  const notes: string[] = []
  let line = `${prefix[node.kind]} ${node.name}`
  const ext = targetsOf(doc, node, 'extends')
  if (ext.length && node.kind !== 'enum') {
    line += ` extends ${ext[0].name}`
    if (ext.length > 1) notes.push(`// NOTE: Dart는 단일 상속만 지원합니다. 추가 extends: ${ext.slice(1).map((n) => n.name).join(', ')}`)
  } else if (ext.length && node.kind === 'enum') {
    notes.push(`// NOTE: enum은 extends를 쓸 수 없습니다: ${ext.map((n) => n.name).join(', ')}`)
  }
  const impl = targetsOf(doc, node, 'implements')
  if (impl.length) line += ` implements ${impl.map((n) => n.name).join(', ')}`
  return { line, notes }
}

function nodeToDart(doc: Doc, node: InterfaceNode): string {
  const out: string[] = [...docComment(node.memo)]
  const { line, notes } = header(doc, node)
  out.push(...notes)

  if (node.kind === 'enum') {
    const values = node.fields.map((f) => f.name)
    if (!values.length) return [...out, `${line} {}`].join('\n')
    return [...out, `${line} {`, ...values.map((v) => `${I}${v},`), '}'].join('\n')
  }

  const body: string[] = []
  const section = (lines: string[]) => {
    if (!lines.length) return
    if (body.length) body.push('')
    body.push(...lines)
  }

  if (node.kind === 'interface' || node.kind === 'abstract') {
    section(node.fields.map((f) => `${I}${getterSig(f)};`))
    section(node.methods.map((m) => `${I}${methodSig(m)};`))
  } else {
    const isModel = node.kind === 'model'
    // 상위 타입의 멤버 (override 판단 + 누락 멤버 스텁)
    const supers = supertypes(doc, node)
    const superFields = new Map<string, Field>()
    const superMethods = new Map<string, Method>()
    const requiredFields = new Map<string, Field>()
    const requiredMethods = new Map<string, Method>()
    for (const { node: s, mustImplement } of supers) {
      for (const f of s.fields) {
        if (!superFields.has(f.name)) superFields.set(f.name, f)
        if (mustImplement && !requiredFields.has(f.name)) requiredFields.set(f.name, f)
      }
      for (const m of s.methods) {
        if (!superMethods.has(m.name)) superMethods.set(m.name, m)
        if (mustImplement && !requiredMethods.has(m.name)) requiredMethods.set(m.name, m)
      }
    }

    // depends 관계 → 생성자로 주입받는 private final 필드 (class만)
    const deps = isModel
      ? []
      : targetsOf(doc, node, 'depends').filter(
          (t) => !node.fields.some((f) => f.type === t.name) && t.kind !== 'enum' && t.kind !== 'model',
        )
    const depFields = deps.map((t) => ({ name: `_${lowerCamel(t.name)}`, type: t.name }))
    const ownFields = node.fields

    const fieldLines: string[] = []
    for (const d of depFields) fieldLines.push(`${I}final ${d.type} ${d.name};`)
    for (const f of ownFields) {
      if (superFields.has(f.name)) fieldLines.push(`${I}@override`)
      fieldLines.push(`${I}final ${formatFieldType(f)} ${f.name};`)
    }
    section(fieldLines)

    // 생성자
    if (depFields.length || ownFields.length || isModel) {
      const positional = depFields.map((d) => `this.${d.name}`)
      const named = ownFields.map((f) => (f.nullable ? `this.${f.name}` : `required this.${f.name}`))
      const parts = [...positional]
      if (named.length) parts.push(`{${named.join(', ')}}`)
      const constKw = isModel || (!depFields.length && !node.methods.length) ? 'const ' : ''
      section([`${I}${constKw}${node.name}(${parts.join(', ')});`])
    }

    // 상위 타입에만 있는 getter는 스텁으로
    const ownFieldNames = new Set(ownFields.map((f) => f.name))
    const missingGetters = [...requiredFields.values()].filter((f) => !ownFieldNames.has(f.name))
    section(missingGetters.flatMap((f) => [`${I}@override`, `${I}${getterSig(f)} => throw UnimplementedError();`]))

    const methodLines: string[] = []
    const ownMethodNames = new Set(node.methods.map((m) => m.name))
    const allMethods = [
      ...node.methods,
      ...[...requiredMethods.values()].filter((m) => !ownMethodNames.has(m.name)),
    ]
    for (const m of allMethods) {
      if (methodLines.length) methodLines.push('')
      if (superMethods.has(m.name)) methodLines.push(`${I}@override`)
      methodLines.push(`${I}${methodSig(m)} => throw UnimplementedError();`)
    }
    section(methodLines)
  }

  if (!body.length) return [...out, `${line} {}`].join('\n')
  return [...out, `${line} {`, ...body, '}'].join('\n')
}
